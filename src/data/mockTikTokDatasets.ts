/**
 * Builds fully analyzed CommentItem objects using VADER and Hugging Face
 */
export function processRawComments(rawList: TikTokProjectData['rawComments']): CommentItem[] {
  return rawList.map((raw) => {
    const vader = analyzeVader(raw.text);
    const huggingFace = analyzeHuggingFaceEmotion(raw.text);

    return {
      id: raw.id,
      author: raw.author,
      username: raw.username,
      avatar: raw.avatar,
      text: raw.text,
      likes: raw.likes,
      timeAgo: raw.timeAgo,
      timestamp: Date.now() - Math.floor(Math.random() * 1000 * 60 * 120),
      vader,
      huggingFace,
      themes: raw.themes,
      isPinned: raw.isPinned,
      isAlertTrigger: huggingFace.primaryEmotion === 'outrage' || huggingFace.primaryEmotion === 'sarcasm',
    };
  });
}
